/**
 * The cliff field laid at a density of its own, for the tests that test
 * what it lays. `CLIFF_DENSITY` stands at 0, so the shipped field puts no
 * module on any face and the cliff pass makes no collider; these tests lay
 * it at `CLIFF_LAID`, the share the modules stood at, so what they pin is
 * still the field's own work and holds when the modules return.
 */
import { generateChunkWith, registeredPasses, type Chunk, type Pass } from "../../../src/sim/chunk.js";
import type { BoxSource } from "../../../src/sim/boxSource.js";
import { CHUNK_SIZE } from "../../../src/sim/forestConstants.js";
import type { Aabb } from "../../../src/sim/level.js";
import type { Vec3 } from "../../../src/sim/types.js";
import {
  cachedCliffCellBoxes, cliffChunkProps, type CliffCellSource,
} from "../../../src/sim/passes/cliffs.js";

/** The share of cells that start a run when these tests lay the field. */
export const CLIFF_LAID = 0.1;

/** The cells' modules and colliders at `CLIFF_LAID`, remembered. */
export const laidCells: CliffCellSource = (seed, ci, cj) => cachedCliffCellBoxes(seed, ci, cj, CLIFF_LAID);

/** The registered passes, with the cliff pass (id 10) laying at
 * `CLIFF_LAID`: its own tunables and its own emitter, fed the laid cells. */
export function laidPasses(): Pass[] {
  return registeredPasses().map((p) => (p.id === 10
    ? { id: p.id, name: p.name, tunables: p.tunables, run: (chunk: Chunk, seed: number) => cliffChunkProps(chunk, seed, laidCells) }
    : p));
}

/** A chunk generated by `laidPasses`. */
export function laidChunk(seed: number, cx: number, cz: number): Chunk {
  return generateChunkWith(laidPasses(), seed, cx, cz);
}

/** The chunk grid's broadphase over chunks generated by `laidPasses`: the
 * same canonical walk, (cx, cz) ascending, as `chunkGrid.ts`. */
export function laidGrid(seed: number): BoxSource & { chunkAt(cx: number, cz: number): Chunk } {
  const passes = laidPasses();
  const chunks = new Map<string, Chunk>();
  const scratch: Aabb[] = [];
  function chunkAt(cx: number, cz: number): Chunk {
    const key = `${cx},${cz}`;
    let c = chunks.get(key);
    if (c === undefined) {
      c = generateChunkWith(passes, seed, cx, cz);
      chunks.set(key, c);
    }
    return c;
  }
  function near(min: Vec3, max: Vec3): readonly Aabb[] {
    scratch.length = 0;
    for (let cx = Math.floor(min.x / CHUNK_SIZE); cx <= Math.floor(max.x / CHUNK_SIZE); cx++) {
      for (let cz = Math.floor(min.z / CHUNK_SIZE); cz <= Math.floor(max.z / CHUNK_SIZE); cz++) {
        for (const { box } of chunkAt(cx, cz).props) {
          if (box.max.x < min.x || box.min.x > max.x) continue;
          if (box.max.y < min.y || box.min.y > max.y) continue;
          if (box.max.z < min.z || box.min.z > max.z) continue;
          scratch.push(box);
        }
      }
    }
    return scratch;
  }
  return { near, chunkAt };
}
