#!/usr/bin/env node
// Builds the simulation's field kernel (client/rust/field, Rust) to WebAssembly and writes it, as text, into
// client/src/sim/kernel/fieldWasm.ts, which is committed: the game, its tests and its builds read that file and
// need no Rust. Run it after changing anything under client/rust/ (npm run kernel:build); it needs rustup, which
// takes the compiler and the wasm32-unknown-unknown target from client/rust/rust-toolchain.toml.
//
//   node tools/rust/build.mjs           builds and writes the module
//   node tools/rust/build.mjs --check   builds and fails if the committed module is not what the sources make
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { kernelSourceHash } from './lib/stamp.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const crate = join(root, 'client/rust/field');
const out = join(root, 'client/src/sim/kernel/fieldWasm.ts');
const check = process.argv.includes('--check');

// The checkout's own path is kept out of the module, so two machines make the same bytes.
execFileSync('cargo', ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
  env: { ...process.env, RUSTFLAGS: `--remap-path-prefix=${root}=.` },
});
const wasm = readFileSync(join(crate, 'target/wasm32-unknown-unknown/release/dayhike_field.wasm'));
const base64 = wasm.toString('base64');
const text = [
  '// GENERATED by tools/rust/build.mjs from client/rust/field (npm run kernel:build). Not written by hand.',
  '// The simulation\'s field kernel as WebAssembly, in base64: client/src/sim/fieldKernel.ts instantiates it.',
  `/** SHA-256 of the sources this was built from (tools/rust/lib/stamp.mjs); the tools suite compares it with them. */`,
  `export const FIELD_WASM_SOURCE_SHA256 = "${kernelSourceHash(root)}";`,
  `/** The module's bytes: ${wasm.length}. */`,
  `export const FIELD_WASM_BASE64 =`,
  `  "${base64}";`,
  '',
].join('\n');

if (check) {
  const committed = readFileSync(out, 'utf8');
  if (committed !== text) {
    console.error('the committed kernel module is not what client/rust/field builds to: run npm run kernel:build');
    process.exit(1);
  }
  console.log(`the committed kernel module is what the sources build to (${wasm.length} bytes)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote client/src/sim/kernel/fieldWasm.ts (${wasm.length} bytes of WebAssembly)`);
}
